"""Regenerate every sprite used by Hollowgate.  Usage: python3 tools/art/build_all.py"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))

import gen_characters
import gen_monsters
import gen_world
import gen_icons


def main():
    sp = os.path.join(ROOT, 'assets', 'sprites')
    manifest = {}
    gen_characters.build_all(os.path.join(sp, 'characters'), manifest)
    gen_monsters.build_all(os.path.join(sp, 'monsters'), manifest)
    gen_world.build_all(os.path.join(sp, 'world'), manifest)
    gen_icons.build_all(os.path.join(sp, 'ui'), manifest)
    os.makedirs(os.path.join(ROOT, 'assets', 'data'), exist_ok=True)
    with open(os.path.join(ROOT, 'assets', 'data', 'art_manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
    # GDScript copy so exported builds never miss the manifest (JSON files are not exported by default)
    with open(os.path.join(ROOT, 'assets', 'data', 'art_manifest.gd'), 'w') as f:
        f.write('extends RefCounted\n## Generated by tools/art/build_all.py - do not edit by hand.\n\nconst DATA := ')
        f.write(json.dumps(manifest, sort_keys=True))
        f.write('\n')
    print('art generated:', len(manifest), 'groups')


if __name__ == '__main__':
    main()
